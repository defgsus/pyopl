import json
import pprint
import textwrap
from copyreg import constructor
from pathlib import Path
import ast



def parse_pyi(filename: str | Path) -> dict[str, str]:
    tree = ast.parse(
        Path(filename).read_text(),
        filename=str(filename),
    )
    doc_strings = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            doc_strings[node.name] = ast.get_docstring(node)
        elif isinstance(node, ast.FunctionDef):
            # don't need to get annotations for @property getters
            if any(
                    isinstance(d, ast.Name) and d.id == "property"
                    or isinstance(d, ast.Attribute) and d.attr == "property"
                    for d in node.decorator_list
            ):
                doc_strings[node.name] = ast.get_docstring(node)
            else:
                arguments = []
                all_args = node.args.posonlyargs + node.args.args
                for i, arg in enumerate(all_args):
                    if arg.arg == "self":
                        continue

                    arguments.append(arg.arg)
                    if arg.annotation:
                        arguments[-1] = f"{arguments[-1]}: {ast.unparse(arg.annotation)}"

                if node.args.defaults:
                    for i, default in enumerate(node.args.defaults):
                        idx = i + len(arguments) - len(node.args.defaults)
                        arguments[idx] = f"{arguments[idx]} = {ast.unparse(default)}"

                arguments = ", ".join(arguments)
                doc_strings[node.name] = (
                    f"{node.name}({arguments})\n--\n\n{ast.get_docstring(node)}"
                )

    return doc_strings


def render_template(
        source_filename: Path,
        target_filename: Path,
        doc_strings: dict[str, str],
):
    text = source_filename.read_text()
    text = (
        f"/*"
        f"\n   DO NOT EDIT THIS FILE!"
        f"\n   It is auto-generated by {Path(__file__).name} and will be overwritten."
        f"\n   Edit this file instead: {source_filename.name}\n*/\n\n{text}"
    )
    for key, doc_string in doc_strings.items():
        text = text.replace(
            f'"{{{{{key}}}}}"',
            json.dumps(doc_string, ensure_ascii=False),
        )

    # extend the class doc-string with the __init__ documentation
    #   because python does not allow documenting the __init__ method in the C-extension :(
    constructor_str = doc_strings['__init__'].split("--\n\n")
    constructor_str = f"{constructor_str[0]}\n{textwrap.indent(constructor_str[1], '    ')}"
    text = text.replace(
        '"{{class}}"',
        json.dumps(
            f"{doc_strings['OPL3Chip']}\n\nConstructor:\n\n{constructor_str}",
            ensure_ascii=False,
        )
    )

    target_filename.write_text(text)


def main():
    source_path = Path(__file__).resolve().parent.parent / "src" / "pyopl"
    doc_strings = parse_pyi(source_path / "_opl3.pyi")
    render_template(
        source_filename=source_path / "_opl3.orig.c",
        target_filename=source_path / "_opl3.c",
        doc_strings=doc_strings,
    )


if __name__ == "__main__":
    main()
